const m=require('./mock.js');
m.ctx.makeDanruPins();const dp={};m.ctx.logs.filter(l=>l.startsWith('DANRU PIN')).forEach(l=>{const x=l.match(/DANRU PIN\s+(.*?)\s+=\s+(\d{6})/);dp[x[1]]=x[2]});
let fails=0;const ok=(c,t)=>{console.log((c?'PASS ':'FAIL ')+t);if(!c)fails++};
const D=dp['Rendi Irawan'],ADM=m.props.ADMIN_PIN;
const G=m.call({action:'d_add',gp:D,name:'Clean Guard'});
// guards cannot inspect
ok(m.call({action:'d_hk_get',gp:G.pin}).err==='auth','a guard cannot open the building check');
ok(m.call({action:'d_eq_get',gp:G.pin}).err==='auth','a guard cannot open the equipment check');
const g=m.call({action:'d_hk_get',gp:D});
ok(g.ok&&g.items.length===12&&g.items[0].en&&g.items[0].id&&g.last===null&&g.open===0,'checklist: 12 default items, bilingual, no check yet');
const all=(okAll,bad)=>g.items.map((x,i)=>({i,ok:bad&&bad.includes(i)?false:okAll,note:bad&&bad.includes(i)?'Dirty, needs cleaning '+i:''}));
ok(m.call({action:'d_hk_save',gp:D,rows:all(true).slice(0,5)}).err==='hk_all','all items must be answered');
ok(m.call({action:'d_hk_save',gp:D,rows:all(true,[2]).map(r=>r.i===2?{i:2,ok:false,note:''}:r)}).err==='hk_note','a Not OK item needs a note');
let r=m.call({action:'d_hk_save',gp:D,rows:all(true,[0,3]),note:'Morning check'});
ok(r.ok&&r.notOk===2,'check saved with 2 Not OK -> 2 actions');
ok(m.sheets.HKChecks.rows.length===2&&m.sheets.HKActions.rows.length===3,'rows in HKChecks and HKActions');
const st=m.call({action:'state',gp:G.pin});
ok(st.hk&&st.hk.open===2,'guard state shows 2 open cleaning actions');
let l=m.call({action:'hk_list',gp:G.pin});
ok(l.ok&&l.open.length===2&&/Dirty/.test(l.open[0].finding),'guard sees the open actions with the finding');
ok(m.call({action:'hk_list',gp:D}).err==='not_guard','supervisors do not use the guard list');
const id0=l.open[0].id;
ok(m.call({action:'hk_done',gp:G.pin,id:id0,note:''}).err==='hk_donenote','guard must describe what he did');
ok(m.call({action:'hk_done',gp:G.pin,id:id0,note:'Mopped twice and disinfected'}).ok,'guard marks it done with a description');
ok(m.call({action:'hk_done',gp:G.pin,id:id0,note:'again please'}).err==='already_closed','cannot be done twice');
ok(m.call({action:'state',gp:G.pin}).hk.open===1,'open count drops to 1');
let dl=m.call({action:'d_hk_list',gp:D});
ok(dl.open.length===1&&dl.done.length===1&&dl.done[0].doneBy==='Clean Guard'&&/Mopped/.test(dl.done[0].doneNote),'supervisor sees it waiting for verification, with who and what');
ok(m.call({action:'d_hk_verify',gp:D,id:id0,ok:false,note:''}).err==='hk_note','re-opening needs a reason');
ok(m.call({action:'d_hk_verify',gp:D,id:id0,ok:false,note:'Still smells'}).ok&&m.call({action:'state',gp:G.pin}).hk.open===2,'supervisor re-opens it: back to 2 open');
const id1=m.call({action:'hk_list',gp:G.pin}).open.find(a=>a.id===id0).id;
m.call({action:'hk_done',gp:G.pin,id:id1,note:'Cleaned again with bleach'});
ok(m.call({action:'d_hk_verify',gp:D,id:id1,ok:true,note:'Good'}).ok&&m.call({action:'d_hk_list',gp:D}).verified.length===1,'supervisor verifies it');
ok(m.call({action:'d_hk_get',gp:D}).last.notOk===2,'last check summary');
// equipment
const e=m.call({action:'d_eq_get',gp:D});
ok(e.ok&&e.items.length===10&&e.last===null,'equipment list: 10 default items');
const rowsE=(f)=>e.items.map((x,i)=>f(x,i));
ok(m.call({action:'d_eq_save',gp:D,rows:rowsE(()=>({found:1,cond:'OK'})).slice(0,3)}).err==='eq_all','all equipment lines must be filled');
ok(m.call({action:'d_eq_save',gp:D,rows:rowsE((x,i)=>({found:1,cond:i===3?'Missing':'OK',note:''}))}).err==='eq_note','Missing needs a note');
ok(m.call({action:'d_eq_save',gp:D,rows:rowsE((x,i)=>({found:x.exp||2,cond:'Wrong',note:''}))}).err==='eq_all','bad condition refused');
m.ctx.setCfg_('EQUIP_ITEMS','Radio|Radio|4;Torch|Senter|0');
const e2=m.call({action:'d_eq_get',gp:D});
ok(e2.items.length===2&&e2.items[0].exp===4,'Config EQUIP_ITEMS overrides the list');
ok(m.call({action:'d_eq_save',gp:D,rows:[{found:3,cond:'OK',note:''},{found:5,cond:'OK',note:''}]}).err==='eq_note','fewer than expected needs a note');
r=m.call({action:'d_eq_save',gp:D,rows:[{found:3,cond:'OK',note:'one radio charging at the office'},{found:5,cond:'Damaged',note:'2 torches broken'}]});
ok(r.ok&&r.issues===2,'equipment saved, 2 issues');
const e3=m.call({action:'d_eq_get',gp:D});
ok(e3.last&&e3.last.by==='Rendi Irawan'&&e3.items[0].last.found===3&&e3.items[1].last.cond==='Damaged','last result is shown per item');
// admin
const o=m.call({action:'a_chk',pin:ADM});
ok(o.ok&&o.checks.length===1&&o.checks[0].notOk===2&&o.open.length===1&&o.eqProblems.length===2&&o.eqLast.by==='Rendi Irawan','admin overview: checks, open actions, equipment problems');
ok(m.call({action:'a_chk',pin:'000000'}).err==='pin','admin overview needs the admin PIN');
ok(m.call({action:'d_hk_save',pin:ADM,rows:all(true)}).ok,'admin PIN can also record a check');
console.log(fails?'FAILED':'ALL PASSED');process.exit(fails?1:0);
